"""Regrowth ablation: saliency pruning with regrow_frac in {0, 0.05, 0.1} at 90% and 95% sparsity.

Run: python -m train.ablate_regrow       (~4 min; writes results/regrow_ablation.json, results/REGROW.md)

Same data, epochs, seeds and paired bootstrap as train/sweep.py. Same seed -> same data,
split and init across regrow fractions, so differences vs regrow 0.0 are paired.
"""
import json

import numpy as np

import train.train_prune as tp
from prune.pruner import Pruner
from train.sweep import DATA_KW, EPOCHS, SEEDS, paired_bootstrap

SPARSITIES = [0.9, 0.95]
FRACS = [0.0, 0.05, 0.1]
CRITERION = "saliency"


class _Recording(Pruner):
    """Behaves exactly like Pruner; only remembers the instance so we can read its stats."""
    last = None

    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        _Recording.last = self


def ablate():
    tp.Pruner = _Recording  # run() builds its own Pruner; this only exposes its .stats
    raw = []
    try:
        for s in SPARSITIES:
            for f in FRACS:
                for seed in SEEDS:
                    model, curve, _ = tp.run(seed=seed, sparsity=s, criterion=CRITERION, epochs=EPOCHS,
                                             regrow_frac=f, data_kw=DATA_KW)
                    raw.append(dict(target=s, regrow_frac=f, seed=seed, achieved=curve[-1]["sparsity"],
                                    test_acc=curve[-1]["test_acc"], **_Recording.last.stats))
                print("done", s, f, flush=True)
    finally:
        tp.Pruner = Pruner
    return raw


def summarize(raw):
    out = {"cells": {}, "paired_vs_no_regrow": {}, "survival": {}}
    for s in SPARSITIES:
        acc = {}
        for f in FRACS:
            rows = sorted([r for r in raw if r["target"] == s and r["regrow_frac"] == f], key=lambda r: r["seed"])
            a = np.array([r["test_acc"] for r in rows])
            acc[f] = a
            key = f"{s}@{f}"
            out["cells"][key] = dict(mean=float(a.mean()), std=float(a.std(ddof=1)), n=len(a),
                                     achieved=float(np.mean([r["achieved"] for r in rows])),
                                     max_sparsity_error=float(max(abs(r["achieved"] - s) for r in rows)))
            if f > 0:
                d = a - acc[0.0]
                lo, hi = paired_bootstrap(d)
                out["paired_vs_no_regrow"][key] = dict(mean_diff=float(d.mean()), ci95=[lo, hi],
                                                       wins=int((d > 0).sum()), ties=int((d == 0).sum()), n=len(d))
                tot = {k: int(sum(r[k] for r in rows)) for k in ("revived", "competed", "moved", "survived")}
                tot["moved_frac"] = tot["moved"] / max(tot["competed"], 1)
                tot["survived_frac"] = tot["survived"] / max(tot["competed"], 1)
                out["survival"][key] = tot
    return out


def write_md(sm):
    n = len(SEEDS)
    txt = (f"# Regrowth ablation (generated by train/ablate_regrow.py)\n\n"
           f"Saliency pruning, 5-arm noisy spirals, 64x64 MLP, {EPOCHS} epochs, {n} paired seeds "
           f"(same data/init per seed). Diff = regrow minus no-regrow test accuracy, 95% paired bootstrap CI.\n\n"
           f"| target | regrow_frac | test acc mean | std | achieved sparsity | diff vs 0.0 (pts) | 95% CI | better/ties |\n"
           f"|---|---|---|---|---|---|---|---|\n")
    for s in SPARSITIES:
        for f in FRACS:
            key = f"{s}@{f}"
            c = sm["cells"][key]
            row = f"| {s*100:.0f}% | {f} | {c['mean']*100:.1f}% | {c['std']*100:.1f} | {c['achieved']*100:.2f}% |"
            if f == 0.0:
                row += " (baseline) | | |"
            else:
                p = sm["paired_vs_no_regrow"][key]
                row += (f" {p['mean_diff']*100:+.2f} | [{p['ci95'][0]*100:+.2f}, {p['ci95'][1]*100:+.2f}] |"
                        f" {p['wins']}/{p['ties']} of {p['n']} |")
            txt += row + "\n"
    excl = [k for k, p in sm["paired_vs_no_regrow"].items() if p["ci95"][0] > 0 or p["ci95"][1] < 0]
    txt += "\n**Verdict:** "
    if not excl:
        txt += ("every 95% CI includes 0. This experiment shows **no reliable accuracy effect** of regrowth "
                "(positive or negative) at these settings. It is a null result.\n")
    else:
        txt += ("the CI excludes 0 for: " + ", ".join(excl) + ". With 4 comparisons, treat a single "
                "borderline exclusion with caution.\n")
    txt += ("\n## Do regrown weights actually live? (summed over seeds)\n\n"
            "Measured at each revived cohort's first prune event after its grace period, i.e. the first time "
            "it competes with established weights.\n\n"
            "| target | regrow_frac | revived | competed | moved off 0 | kept |\n|---|---|---|---|---|---|\n")
    for key, v in sm["survival"].items():
        s, f = key.split("@")
        txt += (f"| {float(s)*100:.0f}% | {f} | {v['revived']} | {v['competed']} | {v['moved_frac']:.1%} | "
                f"{v['survived']} ({v['survived_frac']:.1%}) |\n")
    txt += BEFORE_FIX
    open("results/REGROW.md", "w").write(txt)
    return txt


BEFORE_FIX = """
## Why the pruner changed (diagnostic on the pre-fix code, commit a611eb7, 3 seeds, regrow_frac 0.1)

Revived weights start at w = 0, so their score |w*g| is ~0. Before the fix they were measured at the very
next prune event:

| target | phase | revived weights that had moved off 0 | revived weights kept | other alive weights kept |
|---|---|---|---|---|
| 90% | ramp | 73.2% | 23.4% | 94.3% |
| 90% | fixed sparsity | 20.9% | 0.6% | 99.9% |
| 95% | ramp | 71.0% | 26.6% | 93.4% |
| 95% | fixed sparsity | 6.4% | 0.4% | 100.0% |

At fixed sparsity regrowth was almost pure churn: revive at 0, drop at the next event. A second cause:
growth was ranked by a long EMA of |dense grad|, which kept stale non-zero values for connections into
dead units. In the 64x64 layer 61% of fixed-phase revivals got exactly zero gradient and could never move.

Fixes in prune/pruner.py: (1) revived weights are immune for one prune event (`grace=1`); (2) their score
EMA is reset and bias-corrected (score / (1 - ema^n)), so they are later compared fairly; (3) growth uses
|dense grad| summed over the last interval only, and never picks weights with exactly zero gradient or
weights pruned at the same event. A grace of 2 or 4 events did not raise survival in the same diagnostic,
so revived weights that are then dropped lose on merit, not by construction.

Separately, scores were all zero before the first prune event (dense_grad is None while the mask is all
ones), so the first event cut arbitrary tied weights for both criteria. `accumulate()` now falls back to
p.grad, which equals dL/dW_eff in that case. This changes the no-regrow baseline too, so the regrow 0.0 rows
here do not match results/summary.json, which predates that fix.
"""


if __name__ == "__main__":
    raw = ablate()
    sm = summarize(raw)
    json.dump(dict(raw=raw, summary=sm, settings=dict(sparsities=SPARSITIES, fracs=FRACS, seeds=SEEDS,
                                                      epochs=EPOCHS, data_kw=DATA_KW, criterion=CRITERION)),
              open("results/regrow_ablation.json", "w"), indent=1)
    print(write_md(sm))
